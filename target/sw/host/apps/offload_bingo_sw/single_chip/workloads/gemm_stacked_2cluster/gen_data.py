# The data and sizes of the hardware workload
# offload_bingo_hw/single_chip/workloads/gemm_stacked_2cluster, for the software
# runtime: gemm_data.h (same generator, same seed) and gemm_dims.h (the GEMM
# dimensions and buffer sizes as macros).
import argparse
import importlib.util
import pathlib

HW = (pathlib.Path(__file__).resolve().parents[4]
      / "offload_bingo_hw/single_chip/workloads/gemm_stacked_2cluster")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--hwcfg", type=pathlib.Path, required=True)
    parser.add_argument("--data_h", type=pathlib.Path, required=True)
    parser.add_argument("--dims_h", type=pathlib.Path, required=True)
    args = parser.parse_args()
    spec = importlib.util.spec_from_file_location("gemm_stacked_2cluster_hw", HW / "main_bingo.py")
    hw = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(hw)
    params, merged = hw.define_workload_params(HW / "params.hjson", args.hwcfg)
    args.data_h.write_text(hw.emit_header_file(**merged))
    lines = ["#pragma once", "// Generated by gen_data.py from the hardware workload's parameters"]
    for key in ("M1", "K1", "N1", "M2", "K2", "N2", "arrayShapeIdx", "transposeA", "transposeB",
                "accumPrevC", "num_clusters", "A1_size", "B1_size", "D1_size", "B2_size", "D2_size"):
        lines.append(f"#define GS_{key.upper()} {params[key]}u")
    args.dims_h.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
